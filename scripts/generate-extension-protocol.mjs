/**
 * Writes extension/protocol.js: the Auto port order and the bridge protocol number the browser
 * needs before it can talk to the app, generated from the TypeScript sources that own them
 * (`src/shared/browser-bridge.ts`, `src/main/version.ts`). `--check` compares instead of writing, so
 * the test suite fails whenever a hand edit drifts from the sources.
 */
import { build } from 'esbuild';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'extension', 'protocol.js');

export async function protocolFileText() {
  const dir = mkdtempSync(path.join(os.tmpdir(), 'cos-extension-protocol-'));
  try {
    const data = path.join(dir, 'protocol-data.ts');
    const bundle = path.join(dir, 'protocol-data.mjs');
    const posix = value => value.split(path.sep).join('/');
    writeFileSync(data, [
      `export { BROWSER_BRIDGE_AUTO_PORTS } from ${JSON.stringify(posix(path.join(root, 'src/shared/browser-bridge.ts')))};`,
      `export { BRIDGE_PROTOCOL } from ${JSON.stringify(posix(path.join(root, 'src/main/version.ts')))};`,
      ''
    ].join('\n'));
    await build({ entryPoints: [data], bundle: true, outfile: bundle, format: 'esm', platform: 'node', logLevel: 'error' });
    const values = await import(pathToFileURL(bundle).href);
    return [
      '// Generated by scripts/generate-extension-protocol.mjs from src/shared/browser-bridge.ts and',
      '// src/main/version.ts — do not edit. `npm test` regenerates this file and fails on drift.',
      '',
      `export const PORTS = [${[...values.BROWSER_BRIDGE_AUTO_PORTS].join(', ')}];`,
      `export const BRIDGE_PROTOCOL = ${values.BRIDGE_PROTOCOL};`,
      ''
    ].join('\n');
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const text = await protocolFileText();
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== text) {
    console.error('extension/protocol.js is out of date; run: node scripts/generate-extension-protocol.mjs');
    process.exitCode = 1;
  } else {
    console.log('extension/protocol.js is current');
  }
} else {
  writeFileSync(target, text, 'utf8');
  console.log('wrote extension/protocol.js');
}
